package emulator

import (
	"net/http"

	drive "google.golang.org/api/drive/v3"
)

func (e *Emulator) storeContent(f *File, content []byte) {
	f.Content = append([]byte(nil), content...)
	if e.corrupt > 0 && len(f.Content) > 0 {
		e.corrupt--
		f.Content[len(f.Content)/2] ^= 0xff
	}
	f.md5 = md5Hex(f.Content)
	e.revise(f)
}

type refusal struct {
	code            int
	reason, message string
}

func (no *refusal) write(w http.ResponseWriter) { writeError(w, no.code, no.reason, no.message) }

func (e *Emulator) checkCreate(meta *drive.File) *refusal {
	switch id := meta.Id; {
	case id == "":
	case e.files[id] != nil:
		return &refusal{http.StatusConflict, "fileIdInUse", "A file already exists with the provided ID."}
	case !e.reserved[id]:
		return &refusal{http.StatusBadRequest, "fileIdNotUsable", "The provided ID was not generated by generateIds."}
	}
	for _, p := range meta.Parents {
		pf, ok := e.files[p]
		if !ok || pf.MimeType != MimeFolder {
			return &refusal{http.StatusNotFound, "notFound", "File not found: " + p}
		}
		if pf.CannotAddChildren {
			return denied()
		}
	}
	return nil
}

func denied() *refusal {
	return &refusal{http.StatusForbidden, "insufficientFilePermissions",
		"The user does not have sufficient permissions for this file."}
}

func (e *Emulator) injected(name string) *refusal {
	if fault := e.uploadFault; fault != nil {
		if code := fault(name); code != 0 {
			return &refusal{code, "backendError", "injected failure"}
		}
	}
	return nil
}

func (e *Emulator) commitCreate(meta *drive.File, content []byte) *File {
	id := meta.Id
	if id == "" {
		id = e.newID()
	}
	now := e.now()
	f := &File{ID: id, Name: meta.Name, MimeType: meta.MimeType, Parents: append([]string(nil), meta.Parents...),
		Version: 1, Created: now, Modified: now}
	if f.MimeType == "" {
		f.MimeType = "application/octet-stream"
	}
	if meta.ModifiedTime != "" {
		if t, err := requestTime(meta.ModifiedTime); err == nil {
			f.Modified = t
		}
	}
	e.storeContent(f, content)
	delete(e.reserved, id)
	e.files[id] = f
	e.order = append(e.order, id)
	e.changes = append(e.changes, change{id: id})
	return f
}

func (e *Emulator) commitUpdate(old *File, meta *drive.File, content []byte) *File {
	f := old.bare()
	e.storeContent(&f, content)
	f.Version = old.Version + 1
	f.Modified = e.now()
	if t, err := requestTime(meta.ModifiedTime); err == nil {
		f.Modified = t
	}
	e.files[f.ID] = &f
	e.changes = append(e.changes, change{id: f.ID})
	return &f
}
